"""Schema 1 reports and self-contained, escaped HTML."""

from datetime import datetime, timezone
from html import escape
import json
from pathlib import Path
from typing import Any, Optional

from . import __version__
from .probe import Probe

FOOTER = "Generated by RK Edge Doctor · https://site-ai-gateway.com/open-source/rk-edge-doctor/"
STATUSES = ("pass", "warn", "fail", "skip")


def build_report(checks: list, probe: Probe) -> dict:
    indexed = {item["id"]: item for item in checks}
    soc = indexed["soc"]["value"] or {}
    os_value = indexed["os"]["value"] or {}
    summary = {status: sum(item["status"] == status for item in checks) for status in STATUSES}
    verdict = "CRITICAL" if summary["fail"] else "ATTENTION" if summary["warn"] else "HEALTHY"
    return {
        "schema": 1, "tool_version": __version__,
        "generated_at": datetime.now(timezone.utc).isoformat(),
        "host": {"hostname": probe.system("node") or "unknown",
                 "soc": soc.get("soc", "unknown"),
                 "os": os_value.get("distribution", "unknown"),
                 "kernel": indexed["kernel"]["value"] or "unknown"},
        "summary": summary, "verdict": verdict, "checks": checks,
    }


def display(value: Any) -> str:
    if value is None:
        return "unknown"
    if isinstance(value, str):
        return value.replace("\n", " ").replace("\r", " ")
    return json.dumps(value, ensure_ascii=False, sort_keys=True)


def render_html(report: dict) -> str:
    cards = "".join(
        '<div class="card ' + status + '"><strong>' + str(report["summary"][status])
        + "</strong><span>" + status.upper() + "</span></div>" for status in STATUSES
    )
    rows = []
    for item in report["checks"]:
        cells = [item["id"], item["title"], item["status"].upper(), display(item["value"]),
                 item["detail"], item["hint"] or ""]
        rows.append('<tr id="' + escape(item["id"], quote=True) + '">'
                    + "".join("<td>" + escape(cell) + "</td>" for cell in cells) + "</tr>")
    host = escape(display(report["host"]))
    return """<!doctype html>
<html lang="en"><head><meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<title>RK Edge Doctor board report</title>
<style>
:root{font-family:system-ui,sans-serif;color:#182535;background:#f1f5f9}
body{max-width:1400px;margin:32px auto;padding:0 20px}h1{margin-bottom:8px}
.meta{overflow-wrap:anywhere;color:#475569}.cards{display:flex;gap:16px;flex-wrap:wrap;margin:24px 0}
.card{background:white;border-top:5px solid #64748b;border-radius:6px;padding:16px;min-width:100px}
.card strong{font-size:2rem;display:block}.pass{border-color:#16704a}.warn{border-color:#a16207}.fail{border-color:#b91c1c}
.table{overflow-x:auto;background:white}table{border-collapse:collapse;width:100%;text-align:left}
th,td{padding:12px;border-bottom:1px solid #cbd5e1;vertical-align:top;overflow-wrap:anywhere}
th{background:#e2e8f0}footer{margin:28px 0;font-size:.9rem;overflow-wrap:anywhere}
</style></head><body><h1>RK Edge Doctor</h1>
""" + "<h2>" + escape(report["verdict"]) + '</h2><p class="meta">' + host + "<br>" + (
        "Version " + escape(report["tool_version"]) + " · " + escape(report["generated_at"])
    ) + '</p><div class="cards">' + cards + '</div><div class="table"><table><thead><tr>' + (
        "<th>ID</th><th>Check</th><th>Status</th><th>Value</th><th>Detail</th><th>Hint</th>"
    ) + "</tr></thead><tbody>" + "".join(rows) + "</tbody></table></div><footer>" + escape(FOOTER) + "</footer></body></html>\n"


def write_reports(report: dict, json_path: Optional[str] = None,
                  html_path: Optional[str] = None) -> None:
    if json_path:
        Path(json_path).write_text(json.dumps(report, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    if html_path:
        Path(html_path).write_text(render_html(report), encoding="utf-8")


def terminal_report(report: dict, paths: list) -> str:
    symbols = {"pass": "+", "warn": "!", "fail": "X", "skip": "-"}
    lines = [symbols[item["status"]] + " " + item["id"] + ": " + display(item["value"])
             for item in report["checks"]]
    lines.append(report["verdict"] + " | Reports: " + (", ".join(paths) if paths else "none requested"))
    return "\n".join(lines)
